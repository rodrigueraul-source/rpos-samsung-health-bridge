// Lexical copy of the tested modules for the owner's partial runtime. No services at load.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root=path.resolve(__dirname,'..');
const names=['BridgeIntake.gs','BridgeEndpoint.gs','BridgeDelivery.gs','BridgeNotion.gs',
  'BridgeRuntimeHelpers.gs.txt','BridgeAutomatic.gs'];
const body=names.map(n=>fs.readFileSync(path.join(root,'apps-script',n),'utf8').trimEnd()).join('\n\n');
const text='// Generated by scripts/build_automatic_addon.cjs. Install as BridgeAutomaticRuntime.gs.\n'+
  'var RPOS_BRIDGE_AUTOMATIC_V1_ = (function() {\n'+body+'\n'+
  'return {deliver:rposBridgeAutomaticReceipt_,pending:rposBridgeRunAutomaticPending,preflight:rposBridgeAutomaticPreflight};\n})();\n'+
  'function rposBridgeAutomaticReceipt_(id, properties) { return RPOS_BRIDGE_AUTOMATIC_V1_.deliver(id, properties); }\n'+
  'function rposBridgeRunAutomaticPending() { return RPOS_BRIDGE_AUTOMATIC_V1_.pending(); }\n'+
  'function rposBridgeAutomaticPreflight() { return RPOS_BRIDGE_AUTOMATIC_V1_.preflight(); }\n';
const c=vm.createContext({});vm.runInContext(text,c,{timeout:1000});
if(typeof c.rposBridgeAutomaticReceipt_!=='function'||typeof c.rposBridgeRunAutomaticPending!=='function')throw Error('Missing entry');
const output=path.join(root,'apps-script','BridgeAutomaticRuntime.gs.txt');
if(process.argv.includes('--check')) {
  if(fs.readFileSync(output,'utf8')!==text)throw Error('Stale automatic addon');
  console.log('Automatic addon matches tested modules; isolated globals/load without services PASS');
} else {fs.writeFileSync(output,text);console.log('Generated automatic addon:'+Buffer.byteLength(text)+' bytes');}
