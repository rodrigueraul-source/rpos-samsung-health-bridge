// Reproducible install bundle. Does not include scheduler source or credentials.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const names = ['BridgeIntake.gs', 'BridgeEndpoint.gs', 'BridgeDelivery.gs',
  'BridgeNotion.gs', 'BridgeScheduler.gs', 'BridgeMigration.gs', 'BridgeDiagnostics.gs'];
const output = path.join(root, 'apps-script', 'BridgeRuntime.gs.txt');
const endpointRepair = path.join(root, 'apps-script', 'BridgeEndpoint-ReceiptRead-Repair.txt');
const endpointText = '// BEGIN BridgeEndpoint.gs\n' +
  fs.readFileSync(path.join(root, 'apps-script', 'BridgeEndpoint.gs'), 'utf8').trimEnd() +
  '\n// END BridgeEndpoint.gs\n';
const text = '// Generated by scripts/build_apps_script_bundle.cjs. Add as BridgeRuntime.gs.\n' +
  '// Keep the existing scheduler on its legacy path until live binding review.\n' +
  names.map(name => '\n// BEGIN ' + name + '\n' +
    fs.readFileSync(path.join(root, 'apps-script', name), 'utf8').trimEnd() +
    '\n// END ' + name + '\n').join('');
const declarations = [...text.matchAll(/^function\s+(\w+)\s*\(/gm)].map(m => m[1]);
if (new Set(declarations).size !== declarations.length) throw new Error('Duplicate function declaration');
// Loading must not execute any Apps Script service, network or data mutation.
const context = vm.createContext({});
vm.runInContext(text, context, {timeout: 1000});
for (const name of ['rposBridgePreflight', 'rposBridgeReadinessAudit', 'rposBridgeCreateGymCapture_', 'doPost']) {
  if (typeof context[name] !== 'function') throw new Error('Missing runtime entry');
}
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== text) throw new Error('Stale runtime bundle');
  if (!fs.existsSync(endpointRepair) || fs.readFileSync(endpointRepair, 'utf8') !== endpointText) {
    throw new Error('Stale receipt-read Endpoint repair');
  }
  console.log('Bundle matches seven modules; syntax/global entries/load without side effects PASS');
} else {
  fs.writeFileSync(output, text);
  fs.writeFileSync(endpointRepair, endpointText);
  console.log('Generated BridgeRuntime.gs.txt: ' + Buffer.byteLength(text) + ' bytes');
}
